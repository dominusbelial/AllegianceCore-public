using Allegiance.ClientCore.MonoGame.Assets;
using Allegiance.Core;
using Allegiance.Core.Rendering;
using Microsoft.Xna.Framework;
using Microsoft.Xna.Framework.Graphics;

namespace Allegiance.ClientCore.MonoGame.Rendering;

/// <summary>
/// P589 — <b>distant galaxies / small nebulae as cut-out objects</b>: real
/// telescope objects (galaxies, planetary nebulae, compact nebulae / globular
/// cluster cores) cut out of their photographs so only the object survives
/// (no star fields, no rectangles), with soft feathered alpha edges — "placed
/// like a painting" against the black sky, 2-4 per sector seeded by the cluster
/// id, small planet-like angular sizes, dim enough not to compete with ships
/// or the HUD.
///
/// The processed sprites live under the artwork root in <c>p589obj/</c>
/// (generated by <c>tools/space-objects/</c>, re-runnable/deterministic, with
/// contact sheets + licences + credits in <c>docs/reports/P589_assets/</c>).
/// They are drawn with the same poster path as the planet
/// (<see cref="SkyBillboard"/>), premultiplied so the feathered alpha blends
/// without fringes.
///
/// Toggle: <c>--distant-objects off</c> (ON by default in the black sky).
/// </summary>
public sealed class DistantObjectRenderer : IDisposable
{
    private const string Dir = "p589obj";

    private readonly GraphicsDevice _gd;
    private readonly IAssetSource _assets;
    private readonly Dictionary<string, Texture2D> _textures = new(StringComparer.OrdinalIgnoreCase);
    private readonly HashSet<string> _missing = new(StringComparer.OrdinalIgnoreCase);

    private List<Texture2D> _library = [];
    private bool _listed;
    private List<(Vector3 Dir, float HalfWorld, float HalfDeg, Texture2D Tex, float Bright)> _objects = [];

    public DistantObjectRenderer(GraphicsDevice gd, IAssetSource assets)
    {
        _gd = gd;
        _assets = assets;
    }

    public int LibraryCount => _library.Count;

    /// <summary>Recompute the objects for a cluster (called on sector change).</summary>
    public void SetCluster(DataClusterIGC cluster)
    {
        EnsureListed();
        int count = SpaceObjectMath.DistantCount(cluster.ClusterId, _library.Count);
        var list = new List<(Vector3, float, float, Texture2D, float)>(count);
        for (int i = 0; i < count && _library.Count > 0; i++)
        {
            var o = SpaceObjectMath.PlaceDistant(cluster.ClusterId, i, _library.Count);
            var tex = _library[o.SpriteIndex];
            list.Add((new Vector3(o.Direction.X, o.Direction.Y, o.Direction.Z), o.AngularHalfDeg, o.AngularHalfDeg, tex, o.Brightness));
        }
        _objects = list;
    }

    public void Draw(Matrix view, Matrix projection, Vector3 cameraEye, float shellDist)
    {
        foreach (var (dir, _, halfDeg, tex, bright) in _objects)
        {
            float half = SpaceObjectMath.HalfSizeFromHalfDegrees(halfDeg, shellDist);
            byte b = (byte)Math.Clamp(bright * 255f, 0f, 255f);
            SkyBillboard.Draw(_gd, view, projection, cameraEye, dir, shellDist, half, tex, new Color(b, b, b));
        }
    }

    private void EnsureListed()
    {
        if (_listed) return;
        _listed = true;
        try
        {
            var names = _assets.Enumerate(Dir)
                .Where(n => n.EndsWith(".png", StringComparison.OrdinalIgnoreCase))
                .OrderBy(n => n, StringComparer.Ordinal)
                .ToList();
            foreach (var rel in names)
            {
                var tex = LoadPremultipliedPng(rel);
                if (tex is not null) _library.Add(tex);
            }
        }
        catch (Exception ex)
        {
            if (_missing.Add(Dir))
                Console.WriteLine($"[monogame] distant-object dir '{Dir}' unavailable: {ex.Message} — no distant objects");
        }
    }

    private Texture2D? LoadPremultipliedPng(string rel)
    {
        if (_textures.TryGetValue(rel, out var t)) return t;
        if (_missing.Contains(rel)) return null;
        try
        {
            using var s = _assets.OpenRead(rel);
            var tex = Texture2D.FromStream(_gd, s);
            var data = new Color[tex.Width * tex.Height];
            tex.GetData(data);
            // Premultiply straight-alpha PNG so the feathered edges blend
            // cleanly under BlendState.AlphaBlend (no dark fringes).
            for (int i = 0; i < data.Length; i++)
            {
                float a = data[i].A / 255f;
                data[i] = new Color(
                    (byte)(data[i].R * a),
                    (byte)(data[i].G * a),
                    (byte)(data[i].B * a),
                    data[i].A);
            }
            tex.SetData(data);
            _textures[rel] = tex;
            return tex;
        }
        catch (Exception ex)
        {
            _missing.Add(rel);
            Console.WriteLine($"[monogame] distant-object sprite '{rel}' failed: {ex.Message}");
            return null;
        }
    }

    public void Dispose()
    {
        foreach (var t in _textures.Values) t.Dispose();
        _textures.Clear();
    }
}
