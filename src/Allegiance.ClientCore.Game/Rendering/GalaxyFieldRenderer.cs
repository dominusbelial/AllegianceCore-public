using Allegiance.ClientCore.MonoGame.Assets;
using Allegiance.Core;
using Allegiance.Core.Rendering;
using Microsoft.Xna.Framework;
using Microsoft.Xna.Framework.Graphics;

namespace Allegiance.ClientCore.MonoGame.Rendering;

/// <summary>
/// P589 — the <b>deep-field galaxy field</b> (hundreds of small galaxies,
/// log-distributed sizes, dim) plus the <b>Little Red Dots</b> (procedural JWST
/// early-universe objects, tiny and very red), both drawn as "paintings" on the
/// black sky — the same rules as the planets (object only, feathered edges,
/// fixed direction, dim), seeded per cluster (<see cref="SpaceObjectMath"/>).
///
/// <b>One batched/instanced draw:</b> every galaxy sprite (from the
/// <c>p589gal/</c> cut-out library under the artwork root, generated by
/// <c>tools/space-objects/</c>) is packed into a single <b>atlas texture</b>;
/// each sector's instances are emitted as one <c>VertexPositionColorTexture</c>
/// triangle list sampling the atlas — a single draw call for the whole field
/// regardless of how many hundreds of sprites are on screen. The Little Red Dot
/// sprite is generated procedurally (a soft bright-core dot, no imagery), and
/// tinted red-orange per instance via vertex colour.
///
/// Toggle: <c>--galaxies off</c> (ON by default in the black sky).
/// </summary>
public sealed class GalaxyFieldRenderer : IDisposable
{
    private const string Dir = "p589gal";
    private const int AtlasWidth = 1024;
    private const int Gap = 2;

    /// <summary>The field's shell distance: beyond the farthest star band (6000),
    /// beyond the planet (6650) and the distant objects, so the deep field sits
    /// at the very back of the sky.</summary>
    private const float ShellDistance = 9400f;

    private readonly GraphicsDevice _gd;
    private readonly IAssetSource _assets;

    private readonly List<(byte[] Rgba, int W, int H)> _sprites = [];
    private readonly List<(float U0, float V0, float U1, float V1)> _uvs = [];
    private bool _libraryReady;

    private Texture2D? _atlas;
    private int _lrdAtlasIdx = -1;

    private VertexPositionColorTexture[] _verts = [];
    private short[] _indices = [];

    /// <summary>Number of galaxy sprites placed per sector (hundreds).</summary>
    public int GalaxyCountPerSector { get; set; } = 420;

    /// <summary>Number of Little Red Dots placed per sector (a few dozen).</summary>
    public int LrdCountPerSector { get; set; } = 40;

    public GalaxyFieldRenderer(GraphicsDevice gd, IAssetSource assets)
    {
        _gd = gd;
        _assets = assets;
    }

    public int SpriteCount => _sprites.Count;

    /// <summary>Recompute the field for a cluster (called on sector change):
    /// rebuild the atlas once, then regenerate all instance quads.</summary>
    public void SetCluster(DataClusterIGC cluster)
    {
        EnsureLibrary();
        if (_atlas is null) return;

        var galaxies = SpaceObjectMath.PlaceGalaxies(cluster.ClusterId, GalaxyCountPerSector, _sprites.Count);
        var lrds = SpaceObjectMath.PlaceLittleRedDots(cluster.ClusterId, LrdCountPerSector);

        int galVerts = galaxies.Length * 4;
        int lrdVerts = lrds.Length * 4;
        _verts = new VertexPositionColorTexture[galVerts + lrdVerts];
        _indices = new short[(galaxies.Length + lrds.Length) * 6];

        int vi = 0, ii = 0;
        foreach (var g in galaxies)
        {
            var (u0, v0, u1, v1) = _uvs[g.SpriteIndex % _uvs.Count];
            EmitQuad(ref vi, ref ii, new Vector3(g.Direction.X, g.Direction.Y, g.Direction.Z), g.AngularHalfDeg,
                g.RotationRad, g.Brightness, u0, v0, u1, v1, white: true);
        }
        foreach (var l in lrds)
        {
            var (u0, v0, u1, v1) = _uvs[_lrdAtlasIdx];
            EmitQuad(ref vi, ref ii, new Vector3(l.Direction.X, l.Direction.Y, l.Direction.Z), l.AngularHalfDeg,
                0f, l.Brightness, u0, v0, u1, v1, white: false, hue01: l.Hue);
        }
    }

    /// <summary>Draw the whole field in ONE batched call (the atlas texture
    /// bound once). Depends on the caller's pinned states; sets only blend.</summary>
    public void Draw(Matrix view, Matrix projection, Vector3 cameraEye, float shellDist)
    {
        if (_atlas is null || _verts.Length == 0) return;
        var gd = _gd;
        gd.BlendState = BlendState.AlphaBlend;
        using var effect = new BasicEffect(gd)
        {
            TextureEnabled = true,
            Texture = _atlas,
            VertexColorEnabled = true,
            LightingEnabled = false,
            View = view,
            Projection = projection,
            World = Matrix.Identity,
        };
        foreach (var pass in effect.CurrentTechnique.Passes)
        {
            pass.Apply();
            gd.DrawUserIndexedPrimitives(PrimitiveType.TriangleList, _verts, 0, _verts.Length, _indices, 0, _indices.Length / 3);
        }
    }

    private void EmitQuad(ref int vi, ref int ii, Vector3 dir, float halfDeg, float rot, float bright,
        float u0, float v0, float u1, float v1, bool white, float hue01 = 1f)
    {
        float shellDist = ShellDistance;
        var center = dir * shellDist;
        float half = SpaceObjectMath.HalfSizeFromHalfDegrees(halfDeg, shellDist);

        var baseRight = NativeSkyPlacement.BillboardRight(dir);
        var baseUp = NativeSkyPlacement.BillboardUp(dir, baseRight);
        float c = MathF.Cos(rot), s = MathF.Sin(rot);
        var right = baseRight * c + baseUp * s;
        var up = -baseRight * s + baseUp * c;

        var color = white
            ? new Color((byte)Math.Clamp(255f * bright, 0, 255), (byte)Math.Clamp(255f * bright, 0, 255), (byte)Math.Clamp(255f * bright, 0, 255))
            : HsvToColor(hue01, bright);

        int baseV = vi;
        _verts[vi++] = new VertexPositionColorTexture(center - right * half - up * half, color, new Vector2(u0, v0));
        _verts[vi++] = new VertexPositionColorTexture(center + right * half - up * half, color, new Vector2(u1, v0));
        _verts[vi++] = new VertexPositionColorTexture(center - right * half + up * half, color, new Vector2(u0, v1));
        _verts[vi++] = new VertexPositionColorTexture(center + right * half + up * half, color, new Vector2(u1, v1));

        // Triangle list: (0,1,2) and (2,1,3).
        _indices[ii++] = (short)baseV;
        _indices[ii++] = (short)(baseV + 1);
        _indices[ii++] = (short)(baseV + 2);
        _indices[ii++] = (short)(baseV + 2);
        _indices[ii++] = (short)(baseV + 1);
        _indices[ii++] = (short)(baseV + 3);
    }

    // ------------------------------------------------------------------
    // Library + atlas
    // ------------------------------------------------------------------

    private void EnsureLibrary()
    {
        if (_libraryReady) return;
        _libraryReady = true;
        _sprites.Clear();
        try
        {
            var names = _assets.Enumerate(Dir)
                .Where(n => n.EndsWith(".png", StringComparison.OrdinalIgnoreCase))
                .OrderBy(n => n, StringComparer.Ordinal)
                .ToList();
            foreach (var rel in names)
            {
                var (data, w, h) = LoadPremultipliedPng(rel);
                if (data is not null) _sprites.Add((data, w, h));
            }
        }
        catch (Exception ex)
        {
            Console.WriteLine($"[monogame] galaxy dir '{Dir}' unavailable: {ex.Message}");
        }

        if (_sprites.Count == 0)
            AddFallbackSprites();

        BuildAtlas();
    }

    private (byte[]? Rgba, int W, int H) LoadPremultipliedPng(string rel)
    {
        try
        {
            using var s = _assets.OpenRead(rel);
            using var ms = new MemoryStream();
            s.CopyTo(ms);
            ms.Position = 0;
            var tex = Texture2D.FromStream(_gd, ms);
            int w = tex.Width, h = tex.Height;
            var cols = new Color[w * h];
            tex.GetData(cols);
            var rgba = new byte[cols.Length * 4];
            for (int i = 0; i < cols.Length; i++)
            {
                float a = cols[i].A / 255f;
                rgba[4 * i] = (byte)(cols[i].R * a);
                rgba[4 * i + 1] = (byte)(cols[i].G * a);
                rgba[4 * i + 2] = (byte)(cols[i].B * a);
                rgba[4 * i + 3] = cols[i].A;
            }
            tex.Dispose();
            return (rgba, w, h);
        }
        catch (Exception ex)
        {
            Console.WriteLine($"[monogame] galaxy sprite '{rel}' failed: {ex.Message}");
            return (null, 0, 0);
        }
    }

    /// <summary>If the real library is missing, generate a few procedural soft
    /// galaxy discs so the deep-field still renders (and the tests exercise the
    /// path headlessly with a fake atlas). Shapes: round, elongated-x, elongated-y,
    /// tilted — each a bright-core elliptical disc, feathered.</summary>
    private void AddFallbackSprites()
    {
        foreach (var (ex, ey) in new[] { (1f, 1f), (1.6f, 0.6f), (0.6f, 1.6f), (1.3f, 0.85f) })
        {
            const int S = 64;
            var rgba = new byte[S * S * 4];
            for (int y = 0; y < S; y++)
            for (int x = 0; x < S; x++)
            {
                float nx = (x - S / 2f) / (S / 2f), ny = (y - S / 2f) / (S / 2f);
                float rr = MathF.Sqrt((nx / ex) * (nx / ex) + (ny / ey) * (ny / ey));
                // bright core + soft falloff (rough galaxy profile)
                float core = MathF.Exp(-rr * rr * 5f);
                float halo = MathF.Exp(-rr * rr * 1.2f);
                float v = Math.Clamp(0.25f * halo + 0.75f * core, 0f, 1f);
                int i = (y * S + x) * 4;
                rgba[i] = rgba[i + 1] = rgba[i + 2] = (byte)(v * 255);
                rgba[i + 3] = (byte)(v * 255); // premultiplied
            }
            _sprites.Add((rgba, S, S));
        }
    }

    private void BuildAtlas()
    {
        int x = Gap, y = Gap, rowH = 0;
        var pixRects = new List<Rectangle>();
        int maxBottom = Gap;
        foreach (var (_, w, h) in _sprites)
        {
            if (x + w + Gap > AtlasWidth)
            {
                x = Gap;
                y += rowH + Gap;
                rowH = 0;
            }
            pixRects.Add(new Rectangle(x, y, w, h));
            x += w + Gap;
            rowH = Math.Max(rowH, h);
            maxBottom = Math.Max(maxBottom, y + h);
        }

        // Little Red Dot sprite: 24x24 soft bright-core white dot (tinted red
        // per-instance via vertex colour). Placed in the same shelf flow.
        const int lrd = 24;
        var lrdRgba = BuildLrdSprite(lrd);
        int lrdX = x, lrdY = y;
        if (lrdX + lrd + Gap > AtlasWidth) { lrdX = Gap; lrdY = y + rowH + Gap; }
        maxBottom = Math.Max(maxBottom, lrdY + lrd);

        // Atlas height must cover EVERY blitted region (a row may be taller
        // than the 24px LRD that shares it) — use the true max bottom.
        int atlasH = maxBottom + Gap;
        var atlasData = new Color[AtlasWidth * atlasH];

        _uvs.Clear();
        for (int i = 0; i < _sprites.Count; i++)
        {
            var r = pixRects[i];
            Blit(atlasData, AtlasWidth, r, _sprites[i].Rgba, _sprites[i].W, _sprites[i].H);
            _uvs.Add((
                r.X / (float)AtlasWidth, r.Y / (float)atlasH,
                (r.X + r.Width) / (float)AtlasWidth, (r.Y + r.Height) / (float)atlasH));
        }

        var lrdRect = new Rectangle(lrdX, lrdY, lrd, lrd);
        Blit(atlasData, AtlasWidth, lrdRect, lrdRgba, lrd, lrd);
        _lrdAtlasIdx = _uvs.Count;
        _uvs.Add((
            lrdRect.X / (float)AtlasWidth, lrdRect.Y / (float)atlasH,
            (lrdRect.X + lrdRect.Width) / (float)AtlasWidth, (lrdRect.Y + lrdRect.Height) / (float)atlasH));

        _atlas?.Dispose();
        _atlas = new Texture2D(_gd, AtlasWidth, atlasH, false, SurfaceFormat.Color);
        _atlas.SetData(atlasData);
    }

    private static byte[] BuildLrdSprite(int size)
    {
        var rgba = new byte[size * size * 4];
        for (int y = 0; y < size; y++)
        for (int x = 0; x < size; x++)
        {
            float dx = (x - size / 2f) / (size / 2f), dy = (y - size / 2f) / (size / 2f);
            float rr = MathF.Sqrt(dx * dx + dy * dy);
            float core = MathF.Exp(-rr * rr * 18f);   // bright compact core
            float halo = MathF.Exp(-rr * rr * 3f);    // faint extended halo
            float v = Math.Clamp(0.35f * halo + 0.65f * core, 0f, 1f);
            int i = (y * size + x) * 4;
            rgba[i] = rgba[i + 1] = rgba[i + 2] = (byte)(v * 255);
            rgba[i + 3] = (byte)(v * 255);
        }
        return rgba;
    }

    private static void Blit(Color[] atlas, int atlasW, Rectangle r, byte[] rgba, int sw, int sh)
    {
        for (int yy = 0; yy < sh; yy++)
        {
            int dstBase = (r.Y + yy) * atlasW + r.X;
            int srcBase = yy * sw;
            for (int xx = 0; xx < sw; xx++)
            {
                int si = (srcBase + xx) * 4;
                atlas[dstBase + xx] = new Color(rgba[si], rgba[si + 1], rgba[si + 2], rgba[si + 3]);
            }
        }
    }

    /// <summary>HSV (hue in [0,1] → 0..360°) to RGB, then scaled by
    /// <paramref name="value"/> (brightness). Used to tint Little Red Dots from
    /// deep red through orange-red.</summary>
    private static Color HsvToColor(float hue01, float value)
    {
        float h = (hue01 % 1f + 1f) % 1f * 360f;
        // h 351..375 wraps → 351..360 red-magenta, 0..15 orange-red
        float c = value;
        float hp = h / 60f;
        float x = c * (1f - Math.Abs(hp % 2f - 1f));
        (float r, float g, float b) = hp switch
        {
            < 1 => (c, x, 0f),
            < 2 => (x, c, 0f),
            < 3 => (0f, c, x),
            < 4 => (0f, x, c),
            < 5 => (x, 0f, c),
            _ => (c, 0f, x),
        };
        return new Color((byte)Math.Clamp(r * 255f, 0, 255), (byte)Math.Clamp(g * 255f, 0, 255), (byte)Math.Clamp(b * 255f, 0, 255));
    }

    public void Dispose()
    {
        _atlas?.Dispose();
        _atlas = null;
    }
}
