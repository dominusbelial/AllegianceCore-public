#!/usr/bin/env python3
"""Regenerate client-side ASR/repeat/pitch metadata from the shipping sounddef.

Native factories: effect/efsound.cpp; soundengine/soundtemplates.cpp.
Keep this separate from the core's SoundID catalog: playback is client-only.
"""
import re
from pathlib import Path
from native_cpp_comments import strip_cpp_comments

root = Path(__file__).resolve().parents[1]
mdl = strip_cpp_comments((root / 'src/Allegiance.ClientCore.MonoGame/Content/sounddef.mdl').read_text(encoding='cp1252'))
rows = []
for name, body in re.findall(r'(\w+)\s*=\s*([^;]+);', mdl):
    asr = re.search(r'ASRSound\(\s*([\d.]+)\s*,\s*([\d.]+)', body)
    repeat = re.search(r'RepeatingFireSound\(\s*([\d.]+)', body)
    pitch = re.search(r'PitchSound\(\s*([\d.]+)', body)
    if not (asr or repeat or pitch):
        continue
    values = [float(asr[1]) if asr else 0, float(asr[2]) if asr else 0,
              float(repeat[1]) if repeat else 0, float(pitch[1]) if pitch else 1]
    wave = re.search(r'ImportWave\("([^"]+)"', body)
    stem = '"' + wave[1].lower() + '"' if wave else 'null'
    rows.append(f'            ["{name}"] = new(' + ', '.join(f'{x:g}f' for x in values) + ', ' + stem + '),')
out = root / 'src/Allegiance.ClientCore.Game/Audio/NativeSoundTemplateSettings.Generated.cs'
out.write_text('''// Generated by scripts/generate-client-sound-templates.py; do not edit.
#nullable enable
using Allegiance.Core.Audio;

namespace Allegiance.ClientCore.MonoGame.Audio;

public readonly record struct SoundTemplateSettings(float LoopStartSeconds = 0,
    float LoopSeconds = 0, float RepeatSeconds = 0, float PitchFactor = 1, string? Stem = null)
{
    public SoundTemplateSettings() : this(0, 0, 0, 1, null) { }
    public static SoundTemplateSettings Default => new(PitchFactor: 1);
}

public static class NativeSoundTemplateSettings
{
    public static SoundTemplateSettings Resolve(short id) => NativeSoundCatalog.Resolve(id) is { } template
        ? ByName.GetValueOrDefault(template.Name, SoundTemplateSettings.Default) : SoundTemplateSettings.Default;
    public static IReadOnlyDictionary<string, SoundTemplateSettings> ByName { get; } =
        new Dictionary<string, SoundTemplateSettings>(StringComparer.Ordinal)
        {
''' + '\n'.join(rows) + '''
        }.AsReadOnly();
}
''')
print(f'{len(rows)} client sound templates')
