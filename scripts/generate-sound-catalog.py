#!/usr/bin/env python3
"""Regenerate the native numeric SoundID -> template table (P871 / SIM-0314).

Native builds `m_vSoundMap` by parsing sounddef.mdl's `soundList` through
`TLookup<ISoundTemplate>::Parse(plist, 0, vSoundMap)`
(WinTrek/soundinit.cpp:27-31, engine/value.h:686-722): the FIRST token of each
pair is an index expression (`123` or `<name>SoundId`) and the SECOND is the
template. Later pairs overwrite earlier ones at the same index, and the vector
length is `maxIndex + 1`, which is exactly what `WinTrek::StartSound(SoundID)`
validates against (WinTrek/WinTrek.cpp:11271-11280).

`<name>SoundId` is added to the namespace at runtime by
`SoundInit::AddMembers` from `Igc/sounds.h`: `DEFSOUND(name)` declares the enum
member `<name>Sound`, so `<name>SoundId` resolves to that member's ordinal.

Usage:
    python3 scripts/generate-sound-catalog.py --native-src /path/to/Allegiance/src
"""
import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from native_cpp_comments import strip_cpp_comments  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
CONTENT = ROOT / 'src/Allegiance.ClientCore.MonoGame/Content'
OUT = ROOT / 'src/Allegiance.Core/Audio/NativeSoundCatalog.Generated.cs'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--native-src', required=True, type=Path)
    args = parser.parse_args()

    def clean(text):
        """Drop C/C++ comments the way the native preprocessor does.

        Block comments MUST go first: Igc/sounds.h:443-459 is a
        `/* NYI no turrets ... */` block that itself contains `//` lines, so
        stripping line comments first leaves 13 DEFSOUND names in the enum that
        native never sees (every later id shifts by +13).
        """
        return strip_cpp_comments(text)

    mdl = clean((CONTENT / 'sounddef.mdl').read_text(encoding='cp1252', errors='ignore'))
    enums = re.findall(r'\b(?:DEFSOUND|DEFEMPTYSOUND)\((\w+)\)',
                       clean((args.native_src / 'Igc/sounds.h').read_text(encoding='cp1252', errors='ignore')))
    # Igc/igc.h:459-464 declares `enum { lastDynamicSound = 1000, #include "sounds.h" };`
    # so the first DEFSOUND name is 1001, not 0.
    ids_by_member = {name + 'Sound': 1001 + index for index, name in enumerate(enums)}

    definitions = dict(re.findall(r'(\w+)\s*=\s*([^;]+);', mdl))
    pairs = re.findall(r'\(\s*(\w+)\s*,\s*(\w+)\s*\)', mdl[mdl.index('soundList ='):])

    # TLookup::Parse in list order: later entries overwrite earlier ones.
    table = {}
    count = 0
    for key, template_name in pairs:
        if key.isdigit():
            index = int(key)
        else:
            member = key[:-2] if key.endswith('Id') else key
            if member not in ids_by_member:
                raise SystemExit(f'unresolved soundList key {key}')
            index = ids_by_member[member]
        body = definitions.get(template_name, '')
        waves = sorted({w.lower() for w in re.findall(r'ImportWave\("([^"]+)"', body)})
        looping = 'LoopingSound' in body
        three_d = 'ThreeDSound' in body
        gains = sum(float(g) for g in re.findall(r'GainSound\(\s*(-?[\d.]+)\s*,', body))
        base = -8 if 'SFXGain' in body else -13 if 'VoiceOverGain' in body else 0
        table[index] = (template_name, waves, looping, three_d, base + gains)
        count = max(count, index + 1)

    quote = lambda value: json.dumps(value, ensure_ascii=False)
    lines = [
        '// Generated by scripts/generate-sound-catalog.py; do not edit.',
        '// Native SoundID = sounddef.mdl soundList index (TLookup::Parse, engine/value.h:686-722);',
        '// DEFSOUND names start at 1001 (Igc/igc.h:459-464: enum { lastDynamicSound = 1000, ... }).',
        '// the vector length is maxIndex+1, the bound WinTrek/WinTrek.cpp:11273 checks.',
        '#nullable enable',
        'namespace Allegiance.Core.Audio;',
        '',
        '/// <summary>One resolved native <c>ISoundTemplate</c> (sounddef.mdl).</summary>',
        'public sealed record NativeSoundTemplate(string Name, string[] Waves, bool Looping, bool ThreeDimensional, double GainDb)',
        '{',
        '    public bool Playable => Waves.Length != 0;',
        '}',
        '',
        'public static partial class NativeSoundCatalog',
        '{',
        '    /// <summary>Native <c>m_vSoundMap.GetCount()</c> (max soundList index + 1).</summary>',
        f'    public const int Count = {count};',
        '',
        '    /// <summary>Native <c>m_vSoundMap</c>: index -> template, last soundList write wins.</summary>',
        '    public static IReadOnlyDictionary<short, NativeSoundTemplate> Templates { get; } =',
        '        new Dictionary<short, NativeSoundTemplate>',
        '        {',
    ]
    for index in sorted(table):
        name, waves, looping, three_d, gain = table[index]
        waves_cs = 'new[] { ' + ', '.join(quote(w) for w in waves) + ' }' if waves else '[]'
        lines.append(f'            [{index}] = new({quote(name)}, {waves_cs}, '
                     f'{str(looping).lower()}, {str(three_d).lower()}, {gain:g}),')
    lines += [
        '        }.AsReadOnly();',
        '',
        '    /// <summary>Native <c>DEFSOUND</c> constant name -> SoundID (Igc/igc.h:456-464, Igc/sounds.h).</summary>',
        '    public static IReadOnlyDictionary<string, short> IdsByName { get; } =',
        '        new Dictionary<string, short>',
        '        {',
    ]
    for member, index in sorted(ids_by_member.items()):
        lines.append(f'            [{quote(member)}] = {index},')
    lines += [
        '        }.AsReadOnly();',
        '',
        '    /// <summary>Resolve a native <c>DEFSOUND</c> constant (<c>collisionSound</c>, …).</summary>',
        '    public static short IdOf(string name) => IdsByName.TryGetValue(name, out var id) ? id : (short)-1;',
        '',
        '    /// <summary>The native numeric-template lookup; null for an invalid or empty slot.</summary>',
        '    public static NativeSoundTemplate? Resolve(short soundId)',
        '        => soundId >= 0 && soundId < Count ? Templates.GetValueOrDefault(soundId) : null;',
        '}',
        '',
    ]
    OUT.write_text('\n'.join(lines), newline='\n')
    print(f'wrote {OUT} ({len(table)} templates, {len(ids_by_member)} names, count={count})')


if __name__ == '__main__':
    main()
