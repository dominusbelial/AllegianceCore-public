#!/usr/bin/env python3
"""Regenerate P732's native sound/sonic-chat tables and bundle their real waves.

Usage: python3 scripts/generate-voice-catalog.py --native-src /path/to/Allegiance/src \
    --artwork /path/to/Artwork
The repository's verbatim sounddef.mdl/quickchat.mdl are the definition inputs.
"""
import argparse
import json
from pathlib import Path
import re
import shutil
import sys

ROOT = Path(__file__).resolve().parents[1]
CONTENT = ROOT / 'src/Allegiance.ClientCore.MonoGame/Content'

sys.path.insert(0, str(Path(__file__).resolve().parent))
from native_cpp_comments import strip_cpp_comments  # noqa: E402


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--native-src', required=True, type=Path)
    parser.add_argument('--artwork', required=True, type=Path)
    args = parser.parse_args()
    # Block comments first: Igc/sounds.h:443-459 (`/* NYI no turrets ... */`)
    # holds 13 DEFSOUND names native never sees, so a `//`-only strip shifts
    # every later SoundID by +13. Shared with generate-sound-catalog.py.
    clean = strip_cpp_comments
    mdl = clean((CONTENT / 'sounddef.mdl').read_text())
    qc = clean((CONTENT / 'quickchat.mdl').read_text())
    enums = re.findall(r'\b(?:DEFSOUND|DEFEMPTYSOUND)\((\w+)\)',
                       clean((args.native_src / 'Igc/sounds.h').read_text(encoding='cp1252')))
    ids = {name + 'SoundId': 1001 + i for i, name in enumerate(enums)}
    definitions = dict(re.findall(r'(\w+)\s*=\s*([^;]+);', mdl))
    cues = {}
    for name, body in definitions.items():
        waves = re.findall(r'ImportWave\("([^"]+)"', body)
        if len(waves) != 1 or any(x in body for x in ('LoopingSound', 'ASRSound', 'PairedSound', 'RandomSound')):
            continue
        serial = re.search(r'SerializedSound\((Mutex\w+),\s*([\w.]+),\s*([\d.-]+),\s*(true|false)', body)
        if not serial and name not in ('mountedSound', 'newCriticalMsgSound', 'newNonCriticalMsgSound'):
            continue
        mutex, timeout, priority, single = '', 0., 0., False
        if serial:
            mutex, timeout, priority, single = serial.groups()
            timeout = float(definitions.get(timeout, timeout))
            priority, single = float(priority), single == 'true'
        gain = (-13 if 'VoiceOverGain' in body else -8 if 'SFXGain' in body else 0) + sum(map(float, re.findall(r'GainSound\(\s*(-?[\d.]+)\s*,', body)))
        stem = waves[0].lower()
        cues[name] = (stem, mutex, timeout, priority, single, gain, (args.artwork / (stem + '.ogg')).exists())
    pairs = re.findall(r'\(\s*(\w+)\s*,\s*(\w+)\s*\)', mdl[mdl.index('soundList ='):])
    sound_ids = {int(key) if key.isdigit() else ids[key]: value for key, value in pairs
                 if value in cues and (key.isdigit() or key in ids)}
    sonic_defs = {name: (sound, caption) for name, sound, caption in re.findall(
        r'(\w+)\s*=\s*SonicChat\(\[\s*SonicChatVoice\(\s*(\w+)\s*,\s*"([^"]*)"', qc)}
    sonic = {int(index): sonic_defs[name] for index, name in re.findall(
        r'\(\s*(\d+)\s*,\s*(\w+)\s*\)', qc[qc.index('sonicChats ='):]) if name in sonic_defs}
    needed = set(sound_ids.values()) | {v[0] for v in sonic.values()}
    cues = {k: v for k, v in cues.items() if k in needed}
    quote = lambda v: json.dumps(v, ensure_ascii=False)
    lines = ['// Generated by scripts/generate-voice-catalog.py; do not edit.',
             '// IDs: Igc/igc.h:456-464 + Igc/sounds.h, then sounddef.mdl soundList.',
             'namespace Allegiance.Core.Audio;', '', 'public static partial class NativeVoiceCatalog', '{',
             '    public static IReadOnlyDictionary<string, NativeVoiceCue> Definitions { get; } =',
             '        new Dictionary<string, NativeVoiceCue>', '        {']
    for name, (stem, mutex, timeout, priority, single, gain, available) in sorted(cues.items()):
        lines.append(f'            [{quote(name)}] = new({quote(name)}, {quote(stem)}, {quote(mutex)}, {timeout:g}, {priority:g}, {str(single).lower()}, {gain:g}, {str(available).lower()}),')
    lines += ['        }.AsReadOnly();', '', '    public static IReadOnlyDictionary<short, NativeVoiceCue> Sounds { get; } =',
              '        new Dictionary<short, NativeVoiceCue>', '        {']
    for index, name in sorted(sound_ids.items()):
        lines.append(f'            [{index}] = Definitions[{quote(name)}],')
    lines += ['        }.AsReadOnly();', '', '    public static IReadOnlyDictionary<short, NativeSonicChat> SonicChats { get; } =',
              '        new Dictionary<short, NativeSonicChat>', '        {']
    for index, (name, caption) in sorted(sonic.items()):
        if name in cues:
            lines.append(f'            [{index}] = new({quote(caption)}, Definitions[{quote(name)}]),')
    lines += ['        }.AsReadOnly();', '}', '']
    (ROOT / 'src/Allegiance.Core/Audio/NativeVoiceCatalog.Generated.cs').write_text('\n'.join(lines))
    available = sorted({v[0] for v in cues.values() if v[-1]})
    missing = sorted({v[0] for v in cues.values() if not v[-1]})
    (CONTENT / 'voice-over-manifest.txt').write_text(''.join('Sounds/' + stem + '.ogg\n' for stem in available))
    (CONTENT / 'voice-over-missing.txt').write_text(''.join(stem + '\n' for stem in missing))
    mgcb = (CONTENT / 'Content.mgcb').read_text()
    for stem in available:
        target = CONTENT / 'Sounds' / (stem + '.ogg')
        if not target.exists():
            shutil.copyfile(args.artwork / (stem + '.ogg'), target)
        if '/build:Sounds/' + stem + '.ogg\n' not in mgcb:
            mgcb += f'\n#begin Sounds/{stem}.ogg\n/importer:OggImporter\n/processor:SoundEffectProcessor\n/processorParam:Quality=Best\n/build:Sounds/{stem}.ogg\n'
    (CONTENT / 'Content.mgcb').write_text(mgcb)
    print(f'{len(cues)} definitions; {len(sound_ids)} SoundIDs; {len(sonic)} sonic indices; {len(available)} waves; missing: {missing}')


if __name__ == '__main__':
    main()
