#!/usr/bin/env python3
"""Deterministic conservative dependency closure, unioned with P498's recorded session.

Keep all audio (34 MB) and references from every core/map, so rare voices and
map-selected posters do not depend on which live session happened to be recorded.
No source textures, videos, unused models, or alternate static cores are shipped, except static cores and maps
named by runtime code (training: PCore014.igc + training_*.igc).
"""
import argparse
import json
from pathlib import Path
import re
import subprocess
import struct

REPO = Path(__file__).resolve().parents[1]
TOKEN = re.compile(rb'[A-Za-z_][A-Za-z0-9_./-]*')
EXTENSIONS = ('.mdl', '.cvh', '.png', '.ogg', '.jpg', '.mml')


def generate(art):
    tracked = subprocess.check_output(['git', '-C', str(art), 'ls-files', '-z']).decode().split('\0')
    files = {name: art / name for name in tracked if name and (art / name).is_file()}
    # Preserve case: Linux asset lookup is case sensitive, just as the client is.
    selected = {e['path'] for e in json.loads(
        (REPO / 'docs/reports/P498_ARTWORK_MANIFEST.json').read_text())['files']}
    missing = selected - files.keys()
    if missing:
        raise ValueError(f'Recorded P498 inputs missing: {sorted(missing)}')
    roots = set(selected)

    aliases = {}
    for name in files:
        aliases.setdefault(name, set()).add(name)
        for ext in EXTENSIONS:
            if name.endswith(ext):
                aliases.setdefault(name[:-len(ext)], set()).add(name)

    def references(data):
        found = set()
        for match in TOKEN.finditer(data):
            token = match.group().decode('ascii')
            # IGC's packed numeric bytes can be ASCII immediately before a
            # char[] field, with no token boundary. Match suffixes as well.
            if len(token) > 256:
                continue
            for start in range(len(token)):
                found.update(aliases.get(token[start:], ()))
        return found

    # Runtime literals (including HUD/effects/audio) plus data-driven names from
    # ALL maps and cores, including models/textures/icons in every catalogue.
    # Allegiance.SinglePlayer names the training core (PCore014.igc) and maps (training_*.igc) and the skirmish map.
    for directory in ('src/Allegiance.ClientCore.Game', 'src/Allegiance.Core/MapGen', 'src/Allegiance.SinglePlayer'):
        for p in sorted((REPO / directory).rglob('*.cs')):
            roots.update(references(p.read_bytes()))
    for name, p in sorted(files.items()):
        if p.suffix.lower() == '.igc':
            data = p.read_bytes()
            # The client loads PCore001; other static cores are server data.
            # Map wrappers start with body length, static cores with a version.
            # Native: ~/Development/Allegiance/src/Igc/missionigc.cpp:74-89
            # writes the map body length followed by its bytes; static core
            # version prefix: missionigc.cpp:2363-2365.
            # A static core named by runtime code (training's PCore014.igc) needs its references too.
            if name == 'PCore001.igc' or name in roots or struct.unpack('<i', data[:4])[0] == len(data) - 4:
                roots.update(references(data))
        if p.suffix.lower() == '.ogg':
            roots.add(name)
        # Planet names and HUD gauges/effect frames can be assembled at runtime.
        if p.suffix == '.mdl' and name.startswith(('globe', 'bkgnd', 'lense', 'lens')):
            roots.add(name)
    roots.add('PCore001.igc')
    selected = set(roots)
    pending = list(sorted(roots))
    while pending:
        name = pending.pop()
        if files[name].suffix.lower() not in ('.mdl', '.mml', '.json'):
            continue
        # Compiled MDL imports and text MDL includes both contain ASCII names.
        for dep in sorted(references(files[name].read_bytes()[:65536] if files[name].suffix == '.mdl' and files[name].stat().st_size > 1048576 else files[name].read_bytes()) - selected):
            selected.add(dep)
            pending.append(dep)
    return sorted(roots), sorted(selected), sum(files[n].stat().st_size for n in selected)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--artwork', type=Path, required=True)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    roots, manifest, size = generate(args.artwork)
    for filename, names in [('artwork-roots.txt', roots), ('artwork-manifest.txt', manifest)]:
        target = REPO / 'packaging' / filename
        text = '# Generated by packaging/generate-manifest.py; see packaging/README.md\n' + '\n'.join(names) + '\n'
        if args.check:
            if not target.exists() or target.read_text() != text:
                raise SystemExit(f'{filename} is stale; regenerate and review the diff')
        else:
            target.write_text(text)
    print(f'Artwork: {len(manifest)} files, {size:,} bytes ({size / 2**20:.1f} MiB); {len(roots)} roots')


if __name__ == '__main__':
    main()
